import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { ROOT } from "./lib/procs";

// Turns the last phone E2E run (test-results/e2e-results.json, written by `npm run test:e2e`) into the committed
// evidence index (evidence/MANIFEST.md and evidence/manifest.json) and copies each test's video to evidence/recordings/
// (ignored by Git). The index lists every scenario with its result, duration, per-feature video timestamps and the
// command that reproduces it. Videos supplement the assertions; they certify nothing beyond what the tests check.

const RESULTS = path.join(ROOT, "test-results", "e2e-results.json");
const OUT = path.join(ROOT, "evidence");
const REC = path.join(OUT, "recordings");

if (!fs.existsSync(RESULTS)) {
  console.error(`No E2E results at ${path.relative(ROOT, RESULTS)}. Start the stack (npm run demo) and run npm run test:e2e first.`);
  process.exit(1);
}

type Attachment = { name: string; contentType: string; path?: string };
type Result = { status: string; duration: number; startTime?: string; attachments?: Attachment[]; annotations?: { type: string; description?: string }[]; errors?: { message?: string }[] };
type PwTest = { projectName: string; status?: string; annotations?: { type: string; description?: string }[]; results: Result[] };
type Spec = { title: string; file: string; line: number; tests: PwTest[] };
type Suite = { title: string; file: string; specs?: Spec[]; suites?: Suite[] };

const report = JSON.parse(fs.readFileSync(RESULTS, "utf8")) as { suites: Suite[]; stats: { startTime: string; duration: number; expected: number; unexpected: number; flaky: number; skipped: number } };

function specs(s: Suite[]): Spec[] {
  return s.flatMap((x) => [...(x.specs ?? []), ...specs(x.suites ?? [])]);
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);
const git = (...args: string[]) => {
  try {
    return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    return null;
  }
};

fs.mkdirSync(REC, { recursive: true });
const rows = specs(report.suites).flatMap((spec) =>
  spec.tests.map((t) => {
    const r = t.results[t.results.length - 1];
    const status = r?.status ?? "skipped";
    // Runtime annotations from `mark()` land on the result in newer Playwright versions and on the test in older ones.
    const features = [...(r?.annotations ?? []), ...(t.annotations ?? [])].filter((a) => a.type === "feature").map((a) => a.description ?? "");
    const video = r?.attachments?.find((a) => a.name === "video" && a.path && fs.existsSync(a.path));
    let recording: string | null = null;
    if (video?.path) {
      recording = path.join("recordings", `${slug(path.basename(spec.file, ".spec.ts"))}--${slug(spec.title)}--${t.projectName}.webm`);
      fs.copyFileSync(video.path, path.join(OUT, recording));
    }
    const captures = (r?.attachments ?? []).filter((a) => a.name.startsWith("capture:")).map((a) => a.name.slice("capture:".length));
    return {
      file: `tests/e2e/${spec.file.replace(/^.*tests\/e2e\//, "")}`,
      line: spec.line,
      title: spec.title,
      project: t.projectName,
      status,
      durationMs: r?.duration ?? 0,
      features: [...new Set(features)],
      captures,
      recording,
      error: status === "passed" ? null : (r?.errors?.[0]?.message ?? "").replace(/\u001b\[[0-9;]*m/g, "").split("\n")[0].slice(0, 300) || null,
      reproduce: `npx playwright test ${`tests/e2e/${spec.file.replace(/^.*tests\/e2e\//, "")}`}:${spec.line} --project=${t.projectName}`,
    };
  }),
);

const manifest = {
  generatedAt: new Date().toISOString(),
  run: { startedAt: report.stats.startTime, durationMs: Math.round(report.stats.duration), passed: report.stats.expected, failed: report.stats.unexpected, flaky: report.stats.flaky, skipped: report.stats.skipped },
  build: { commit: git("rev-parse", "--short", "HEAD"), branch: git("rev-parse", "--abbrev-ref", "HEAD"), dirty: Boolean(git("status", "--porcelain", "--", "src", "tests")) },
  scenarios: rows,
};
fs.writeFileSync(path.join(OUT, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

const icon = (s: string) => (s === "passed" ? "passed" : s === "skipped" ? "skipped" : `**${s}**`);
const md = [
  "# Evidence index",
  "",
  `Generated by \`npm run evidence:manifest\` from the phone E2E run of ${report.stats.startTime} on commit \`${manifest.build.commit}\` (${manifest.build.branch}${manifest.build.dirty ? ", with uncommitted changes in src/ or tests/" : ""}).`,
  "",
  `**${manifest.run.passed} passed, ${manifest.run.failed} failed, ${manifest.run.flaky} flaky, ${manifest.run.skipped} skipped** in ${Math.round(manifest.run.durationMs / 1000)} s.`,
  "",
  "Every scenario signs in a separate demo copy, drives the phone UI and asserts on what the screen and the API show. All accounts, money and merchants are synthetic. Videos supplement the assertions; they do not certify production security, legal compliance or third-party coverage.",
  "",
  "## Reproduce",
  "",
  "```sh",
  "npm install && npx playwright install chromium",
  "npm run demo            # starts the bank (3210), the simulated merchant (3211) and the worker",
  "npm run test:e2e        # phone E2E at 390x844, plus 360 and 430 for @layout tests",
  "npm run evidence:manifest",
  "```",
  "",
  "Recordings are copied to `evidence/recordings/`, which Git ignores; rerun the commands above to produce them.",
  "",
  "## Scenarios",
  "",
  ...rows.flatMap((r) => [
    `### ${r.title}`,
    "",
    `- Result: ${icon(r.status)} on ${r.project}, ${(r.durationMs / 1000).toFixed(1)} s`,
    `- Test: [\`${r.file}:${r.line}\`](../${r.file}#L${r.line})`,
    `- Reproduce: \`${r.reproduce}\``,
    ...(r.recording ? [`- Recording: \`evidence/${r.recording}\``] : []),
    ...(r.error ? [`- Failure: ${r.error}`] : []),
    ...(r.features.length ? ["- Video timestamps:", ...r.features.map((f) => `  - ${f}`)] : []),
    "",
  ]),
].join("\n");
fs.writeFileSync(path.join(OUT, "MANIFEST.md"), md);

console.log(`[evidence] ${rows.length} scenarios (${manifest.run.passed} passed, ${manifest.run.failed} failed) -> evidence/MANIFEST.md, evidence/manifest.json; ${rows.filter((r) => r.recording).length} videos -> evidence/recordings/`);
